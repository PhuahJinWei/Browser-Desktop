/**
 * Fetches one still per film for Watch's homepage, and writes them into the repository.
 *
 * Run by hand, never by the build. `npm run sync:stills` reaches the network; `npm run build` must
 * not, and neither must anybody's browser. The whole point of this script is that the fetching
 * happens once, here, on a developer's machine — the site that ships contains the images as
 * ordinary same-origin files and asks Google for nothing. Wiring this into `prebuild` would undo
 * that and make CI depend on YouTube being up, so it is deliberately left out of every lifecycle
 * hook, the same way `sync:models` is.
 *
 * Why this is allowed at all when ADR 20 says "no thumbnails": the rule was never "no images", it
 * was "no requests". A hotlinked thumbnail fires at Google's image host the moment the window
 * opens, before anyone has chosen anything. A file in the build fires at nobody.
 *
 * Why these films and not any others: every entry in the feed is a Blender Foundation open movie,
 * released under CC-BY. A frame from a CC-BY film may be redistributed with attribution, which the
 * homepage gives — the credit line under the grid, plus each card naming its channel. Doing this
 * with an ordinary video would be a copyright problem, and that is a large part of why the feed is
 * curated the way it is.
 *
 * `sharp` is a declared devDependency. If it ever disappears this script stops working, which
 * costs nothing until someone needs to add a film: the stills it already wrote are committed, and
 * the app falls back to a generated poster for anything missing.
 */

import { mkdir, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import sharp from 'sharp';
import { FEED } from '../src/apps/watch/feed.ts';

const OUT = fileURLToPath(new URL('../src/apps/watch/stills/', import.meta.url));

/** Widest first. `maxresdefault` is absent for older uploads, so the fallbacks are not optional. */
const SOURCES = ['maxresdefault', 'sddefault', 'hqdefault', 'mqdefault'];

const WIDTH = 480;
const HEIGHT = 270;

/**
 * YouTube answers a missing size with a 404 on some hosts and a 120x90 grey placeholder on others,
 * so the size of what came back is checked rather than the status alone.
 */
async function fetchStill(id) {
  for (const name of SOURCES) {
    const url = `https://i.ytimg.com/vi/${id}/${name}.jpg`;
    const response = await fetch(url);
    if (!response.ok) continue;
    const buffer = Buffer.from(await response.arrayBuffer());
    const meta = await sharp(buffer).metadata();
    if ((meta.width ?? 0) < 320) continue;
    return { buffer, name, width: meta.width, height: meta.height };
  }
  return null;
}

async function main() {
  await mkdir(OUT, { recursive: true });
  const written = [];

  for (const film of FEED) {
    const got = await fetchStill(film.id);
    if (!got) {
      console.warn(
        `[stills] no usable image for ${film.id} (${film.title}) — it will use a drawn poster`,
      );
      continue;
    }

    // `cover` rather than `contain`: hqdefault and mqdefault arrive in a 4:3 box with the film
    // letterboxed inside it, and cropping to 16:9 is what removes the black bars rather than
    // baking them into the asset.
    const out = await sharp(got.buffer)
      .resize(WIDTH, HEIGHT, { fit: 'cover', position: 'centre' })
      .webp({ quality: 78 })
      .toBuffer();

    await writeFile(path.join(OUT, `${film.id}.webp`), out);
    written.push({ film, source: got.name, from: `${got.width}x${got.height}`, bytes: out.length });
    console.log(
      `[stills] ${film.id}  ${String(out.length).padStart(6)} B  from ${got.name} (${got.width}x${got.height})  ${film.title}`,
    );
  }

  const total = written.reduce((sum, entry) => sum + entry.bytes, 0);
  console.log(
    `[stills] ${written.length}/${FEED.length} written, ${(total / 1024).toFixed(0)} kB total`,
  );

  const readme = [
    '# Watch homepage stills',
    '',
    'Generated by `npm run sync:stills` (`tools/fetch-watch-stills.mjs`). Do not edit by hand.',
    '',
    'One frame per film, resized to ' + WIDTH + 'x' + HEIGHT + ' and encoded as WebP. They are',
    'committed so that the shipped site serves them from its own origin and contacts nobody — see',
    'the addendum to `docs/adr/0020-one-frame-you-asked-for.md`.',
    '',
    'Every film is a Blender Foundation open movie released under CC-BY, which is what makes',
    'redistributing a frame of it possible. Attribution is given on the homepage itself.',
    '',
    '| File | Film | Channel |',
    '| --- | --- | --- |',
    ...written.map(
      (entry) => `| \`${entry.film.id}.webp\` | ${entry.film.title} | ${entry.film.channel} |`,
    ),
    '',
  ].join('\n');
  await writeFile(path.join(OUT, 'README.md'), readme);

  const onDisk = (await readdir(OUT)).filter((name) => name.endsWith('.webp'));
  const orphans = onDisk.filter((name) => !FEED.some((film) => `${film.id}.webp` === name));
  if (orphans.length) {
    console.warn(`[stills] ${orphans.length} file(s) no longer in the feed: ${orphans.join(', ')}`);
  }
}

await main();
